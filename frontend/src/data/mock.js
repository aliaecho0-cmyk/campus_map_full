/** 名称 → 唯一 clubId（去空格与引号） */
function slug(name) {
  return String(name).toLowerCase().replace(/[\s'"“”‘’]/g, '');
}

/** 按坐标归到热力区（新数据只有 X/Y，此处按空间区域近似划分） */
function deriveZone(x, y) {
  if (y <= 3) return 'north-corridor';       // 顶部两排
  if (x <= 1) return 'west-corridor';        // 最左列
  if (x >= 18) return 'east-corridor';       // 最右列
  if (y >= 24) return x <= 4 ? 'west-corridor' : 'south-corridor'; // 底部：左半西走廊、右半南通道
  if (y >= 21 && x >= 9) return 'pool-edge'; // 池边下段
  return 'plaza';                             // 中间下沉广场
}

/** 按坐标/热力区归到大分区（A/B/C/D） */
function deriveArea(x, zone) {
  if (zone === 'north-corridor') return 'B';
  if (zone === 'south-corridor') return 'C';
  if (zone === 'west-corridor') return 'A';
  if (zone === 'east-corridor' || zone === 'pool-edge') return 'D';
  return x <= 4 ? 'A' : 'D'; // plaza：左半 A、右半 D
}

